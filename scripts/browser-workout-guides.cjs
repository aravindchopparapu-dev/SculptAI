/* oxlint-disable typescript/no-require-imports -- Local browser test tooling */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const {emptyState,exercises}=await import('../lib/fitness.ts');
  const {applyAction}=await import('../lib/actions.ts');
  let state=emptyState();
  state.profile={name:'Visual tester',age:30,sex:'Male',height:175,weight:75,goal:'Muscle gain',days:3,minutes:60,equipment:'Gym',experience:'Intermediate',activity:1.375,units:'Metric',diet:'Omnivore',exclusions:'',avoid:'',eligible:true};
  state=applyAction(state,{type:'safety',accepted:true,status:'clear'});
  state=applyAction(state,{type:'readiness',beforePlan:true,readiness:{dayIndex:0,energy:4,soreness:1,minutes:60,pain:false,equipment:'Gym'}});
  const moves=['Dumbbell bench press','Incline dumbbell press','Cable chest fly','Dumbbell curl','Incline dumbbell curl','Hammer curl'].map(name=>({...exercises.find(e=>e.name===name),sets:2,reps:'8-12',rest:60}));
  const day={name:'Chest + Biceps',exercises:moves};
  state=applyAction(state,{type:'proposeCustomWorkout',selectedMuscles:['Chest','Biceps'],day,readinessId:state.readiness.at(-1).id});
  state=applyAction(state,{type:'acceptCustomWorkout',draftId:state.draftWorkout.id,confirmed:true});
  const originalId=state.plans[0].id;
  const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});let revision=0;const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.route('**/api/state',async route=>{if(route.request().method()==='POST'){state=applyAction(state,route.request().postDataJSON().action);revision++;}await route.fulfill({json:{state,revision,user:{name:'Visual tester',email:'fictional@example.test'}}});});
    await page.route('**/api/training/generate',route=>{assert.equal(route.request().postDataJSON().regeneratePlanId,originalId);return route.fulfill({json:{day,rationale:'Test variation preview.',readinessId:state.readiness.at(-1).id}});});
    await page.goto('http://localhost:3001/',{waitUntil:'networkidle'});
    await page.getByRole('tab',{name:'My training',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'Start workout',exact:true}).count(),0);
    assert.equal(await page.getByRole('tab',{name:'Weekly review'}).count(),0);
    await page.locator('.saved-workout').scrollIntoViewIfNeeded();
    assert.equal(await page.locator('.saved-workout details').evaluate(el => el.open),false);
    await page.locator('.saved-workout summary').click();
    assert.equal(await page.locator('.saved-workout details').evaluate(el => el.open),true);
    await page.screenshot({path:'outputs/workout-guides/desktop.png'});
    const guide=page.getByRole('button',{name:'Play movement guide',exact:true}).first();await guide.click();
    await page.getByRole('button',{name:'Next position',exact:true}).first().click();
    await page.waitForFunction(() => { const img=document.querySelector('.saved-workout img');return img && img.complete && img.naturalWidth>0; });
    await page.getByRole('button',{name:'Regenerate workout',exact:true}).click();
    await page.getByText('Test variation preview.').waitFor();
    assert.equal(state.plans[0].id,originalId);
    await page.getByRole('button',{name:'Save this workout'}).click();
    await page.getByText('Test variation preview.').waitFor({state:'hidden'});
    assert.equal(state.plans.length,1);assert.notEqual(state.plans[0].id,originalId);
    await page.getByText('✓ Workout saved. You can find it here whenever you return to My training.').waitFor();
    assert.equal(await page.locator('#saved-workouts').evaluate(el => document.activeElement === el), true);
    await page.reload({waitUntil:'networkidle'});
    await page.getByRole('tab',{name:'My training',exact:true}).click();
    await page.getByRole('heading',{name:'Saved workouts (1)',exact:true}).waitFor();
    assert.equal(await page.locator('.saved-workout').count(),1);
    const summary=page.locator('.saved-workout summary');
    assert.match(await summary.innerText(),/Chest \+ Biceps/);
    await summary.focus();await page.keyboard.press('Enter');
    assert.equal(await page.locator('.saved-workout details').evaluate(el => el.open),true);
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('.saved-workout details').evaluate(el => el.open),false);
    await summary.click();
    await page.setViewportSize({width:360,height:800});await page.locator('.saved-workout').scrollIntoViewIfNeeded();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await page.screenshot({path:'outputs/workout-guides/mobile.png'});
    await page.getByRole('button',{name:'Delete workout',exact:true}).click();
    await page.getByRole('button',{name:'Confirm & save',exact:true}).click();
    await page.locator('.saved-workout').waitFor({state:'hidden'});assert.equal(state.plans.length,0);
    await page.getByRole('tab',{name:'Insights',exact:true}).click();assert.equal(await page.getByRole('heading',{name:'Workout history'}).count(),0);
    assert.deepEqual(errors,[]);console.log('PASS artwork, guide controls, no logging UI, regenerate preview/save, delete and mobile width.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
